// Package gen generates the relay client from cyber-relay's docs/openapi.json:
// the wire types, one Client method per operation, and the operation table
// the relay command dispatches on. Sub-key management (/v1/keys*) is skipped,
// and so is every schema only it uses.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os/exec"
	"sort"
	"strings"
)

// Skipped is the path prefix left out of the client.
const Skipped = "/v1/keys"

// Fetch downloads docs/openapi.json of cyber-relay at ref with the GitHub CLI.
// The repository is private: the caller needs read access to it.
func Fetch(ref string) ([]byte, error) {
	cmd := exec.Command("gh", "api", "-H", "Accept: application/vnd.github.raw",
		"repos/chainreactors/cyber-relay/contents/docs/openapi.json?ref="+ref)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("fetch openapi.json at %s: %w: %s", ref, err, strings.TrimSpace(stderr.String()))
	}
	return out, nil
}

type schema struct {
	Ref                  string             `json:"$ref"`
	Type                 string             `json:"type"`
	Format               string             `json:"format"`
	Description          string             `json:"description"`
	Properties           map[string]*schema `json:"properties"`
	Required             []string           `json:"required"`
	Items                *schema            `json:"items"`
	AdditionalProperties json.RawMessage    `json:"additionalProperties"`
	AllOf                []*schema          `json:"allOf"`
	Enum                 []string           `json:"enum"`
}

type parameter struct {
	Name        string  `json:"name"`
	In          string  `json:"in"`
	Description string  `json:"description"`
	Required    bool    `json:"required"`
	Schema      *schema `json:"schema"`
}

type media struct {
	Content map[string]struct {
		Schema *schema `json:"schema"`
	} `json:"content"`
}

type operation struct {
	ID          string                `json:"operationId"`
	Summary     string                `json:"summary"`
	Description string                `json:"description"`
	Tags        []string              `json:"tags"`
	Parameters  []parameter           `json:"parameters"`
	RequestBody *media                `json:"requestBody"`
	Responses   map[string]media      `json:"responses"`
	Security    []map[string][]string `json:"security"`

	method, path string
}

type document struct {
	Paths      map[string]map[string]json.RawMessage `json:"paths"`
	Components struct {
		Schemas map[string]*schema `json:"schemas"`
	} `json:"components"`
}

type generator struct {
	schemas map[string]*schema
	request map[string]bool // schemas reachable from a request body
	used    map[string]bool
	imports map[string]bool
	out     bytes.Buffer
}

// Generate returns the formatted Go source of api.gen.go.
func Generate(spec []byte, ref string) ([]byte, error) {
	var doc document
	if err := json.Unmarshal(spec, &doc); err != nil {
		return nil, fmt.Errorf("parse openapi.json: %w", err)
	}
	g := &generator{schemas: doc.Components.Schemas, request: map[string]bool{}, used: map[string]bool{}, imports: map[string]bool{"context": true}}
	var ops []*operation
	for path, methods := range doc.Paths {
		if strings.HasPrefix(path, Skipped) {
			continue
		}
		for method, raw := range methods {
			switch method {
			case "get", "post", "put", "patch", "delete":
			default:
				continue
			}
			op := &operation{method: strings.ToUpper(method), path: path}
			if err := json.Unmarshal(raw, op); err != nil {
				return nil, fmt.Errorf("%s %s: %w", method, path, err)
			}
			if op.ID == "" {
				return nil, fmt.Errorf("%s %s has no operationId", method, path)
			}
			ops = append(ops, op)
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].ID < ops[j].ID })
	for _, op := range ops {
		if body := op.body(); body != nil {
			g.mark(body, true)
		}
		g.mark(op.response(), false)
	}
	g.mark(&schema{Ref: "#/components/schemas/RelayError"}, false)

	if err := g.types(); err != nil {
		return nil, err
	}
	for _, op := range ops {
		if err := g.method(op); err != nil {
			return nil, err
		}
	}
	if err := g.table(ops); err != nil {
		return nil, err
	}
	var file bytes.Buffer
	fmt.Fprintf(&file, "// Code generated by tools/relay/internal/gen from cyber-relay docs/openapi.json at %s. DO NOT EDIT.\n\npackage relay\n\nimport (\n", ref)
	imports := make([]string, 0, len(g.imports))
	for path := range g.imports {
		imports = append(imports, path)
	}
	sort.Strings(imports)
	for _, path := range imports {
		fmt.Fprintf(&file, "%q\n", path)
	}
	file.WriteString(")\n\n")
	file.Write(g.out.Bytes())
	src, err := format.Source(file.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w\n%s", err, file.String())
	}
	return src, nil
}

func (g *generator) printf(format string, args ...any) { fmt.Fprintf(&g.out, format, args...) }

func (op *operation) body() *schema {
	if op.RequestBody == nil {
		return nil
	}
	return op.RequestBody.Content["application/json"].Schema
}

// response is the schema of the first 2xx answer.
func (op *operation) response() *schema {
	codes := make([]string, 0, len(op.Responses))
	for code := range op.Responses {
		if strings.HasPrefix(code, "2") {
			codes = append(codes, code)
		}
	}
	sort.Strings(codes)
	if len(codes) == 0 {
		return nil
	}
	return op.Responses[codes[0]].Content["application/json"].Schema
}

func refName(s *schema) string {
	if s == nil {
		return ""
	}
	if s.Ref != "" {
		return strings.TrimPrefix(s.Ref, "#/components/schemas/")
	}
	if len(s.AllOf) == 1 {
		return refName(s.AllOf[0])
	}
	return ""
}

func (g *generator) mark(s *schema, request bool) {
	if s == nil {
		return
	}
	if name := refName(s); name != "" {
		if g.used[name] && (!request || g.request[name]) {
			return
		}
		g.used[name] = true
		if request {
			g.request[name] = true
		}
		s = g.schemas[name]
		if s == nil {
			return
		}
	}
	for _, p := range s.Properties {
		g.mark(p, request)
	}
	g.mark(s.Items, request)
	if extra := additional(s); extra != nil {
		g.mark(extra, request)
	}
}

// additional decodes additionalProperties; {} and true mean any value.
func additional(s *schema) *schema {
	if len(s.AdditionalProperties) == 0 || string(s.AdditionalProperties) == "false" {
		return nil
	}
	var extra schema
	if json.Unmarshal(s.AdditionalProperties, &extra) != nil {
		return &schema{}
	}
	return &extra
}

func (g *generator) types() error {
	names := make([]string, 0, len(g.used))
	for name := range g.used {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		s := g.schemas[name]
		if s == nil {
			return fmt.Errorf("schema %s is referenced but not defined", name)
		}
		g.comment(s.Description)
		if len(s.Enum) > 0 {
			if s.Type != "string" {
				return fmt.Errorf("schema %s: only string enums are supported", name)
			}
			g.printf("type %s string\n\nconst (\n", typeName(name))
			for _, value := range s.Enum {
				g.printf("%s %s = %q\n", typeName(name)+fieldName(value), typeName(name), value)
			}
			g.printf(")\n\n")
			continue
		}
		if s.Type != "object" {
			return fmt.Errorf("schema %s: unsupported type %q", name, s.Type)
		}
		g.printf("type %s struct {\n", typeName(name))
		if err := g.fields(name, s); err != nil {
			return err
		}
		g.printf("}\n\n")
	}
	return nil
}

func (g *generator) fields(owner string, s *schema) error {
	required := map[string]bool{}
	for _, name := range s.Required {
		required[name] = true
	}
	props := make([]string, 0, len(s.Properties))
	for name := range s.Properties {
		props = append(props, name)
	}
	sort.Strings(props)
	for _, name := range props {
		p := s.Properties[name]
		typ, err := g.goType(p, g.request[owner], required[name])
		if err != nil {
			return fmt.Errorf("%s.%s: %w", owner, name, err)
		}
		tag := name
		if !required[name] {
			tag += ",omitempty"
		}
		g.comment(p.Description)
		g.printf("%s %s `json:%q`\n", fieldName(name), typ, tag)
	}
	return nil
}

func (g *generator) goType(s *schema, request, required bool) (string, error) {
	if name := refName(s); name != "" {
		return typeName(name), nil
	}
	switch s.Type {
	case "string":
		if s.Format == "date-time" {
			g.imports["time"] = true
			if required {
				return "time.Time", nil
			}
			return "*time.Time", nil
		}
		return "string", nil
	case "integer":
		if s.Format == "int64" {
			return "int64", nil
		}
		return "int", nil
	case "number":
		return "float64", nil
	case "boolean":
		// An optional request flag must be able to send an explicit false
		// (cache defaults to true).
		if request && !required {
			return "*bool", nil
		}
		return "bool", nil
	case "array":
		if s.Items == nil {
			return "", fmt.Errorf("array without items")
		}
		item, err := g.goType(s.Items, request, true)
		return "[]" + item, err
	case "object":
		if len(s.Properties) > 0 {
			return "", fmt.Errorf("inline object schemas are not supported")
		}
		extra := additional(s)
		if extra == nil || (extra.Type == "" && refName(extra) == "") {
			return "map[string]any", nil
		}
		value, err := g.goType(extra, request, true)
		return "map[string]" + value, err
	case "":
		g.imports["encoding/json"] = true
		return "json.RawMessage", nil
	}
	return "", fmt.Errorf("unsupported type %q", s.Type)
}

func (g *generator) comment(text string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	for _, line := range strings.Split(text, "\n") {
		g.printf("// %s\n", strings.TrimRight(line, " "))
	}
}

// signature splits an operation's parameters and names its body and answer types.
func (g *generator) signature(op *operation) (params []parameter, query []parameter, body, out string, err error) {
	for _, p := range op.Parameters {
		switch p.In {
		case "path":
			params = append(params, p)
		case "query":
			query = append(query, p)
		default:
			return nil, nil, "", "", fmt.Errorf("%s: parameter %s in %s is not supported", op.ID, p.Name, p.In)
		}
	}
	if s := op.body(); s != nil {
		if body = refName(s); body == "" {
			return nil, nil, "", "", fmt.Errorf("%s: request body must be a named schema", op.ID)
		}
		body = typeName(body)
	}
	if out = refName(op.response()); out == "" {
		return nil, nil, "", "", fmt.Errorf("%s: 2xx response must be a named schema", op.ID)
	}
	return params, query, body, typeName(out), nil
}

func (g *generator) method(op *operation) error {
	path, query, body, out, err := g.signature(op)
	if err != nil {
		return err
	}
	name := methodName(op.ID)
	if len(path) > 0 || len(query) > 0 {
		g.imports["net/url"] = true
	}
	args := []string{"ctx context.Context"}
	for _, p := range path {
		args = append(args, argName(p.Name)+" string")
	}
	if body != "" {
		args = append(args, "body "+body)
	}
	if len(query) > 0 {
		args = append(args, "params "+name+"Params")
		g.printf("// %sParams are the query parameters of %s.\ntype %sParams struct {\n", name, name, name)
		for _, p := range query {
			typ := map[string]string{"string": "string", "integer": "int", "boolean": "bool"}[p.Schema.Type]
			if typ == "" {
				return fmt.Errorf("%s: query parameter %s has type %q", op.ID, p.Name, p.Schema.Type)
			}
			g.comment(p.Description)
			g.printf("%s %s `json:%q`\n", fieldName(p.Name), typ, p.Name+",omitempty")
		}
		g.printf("}\n\nfunc (p %sParams) values() url.Values {\nv := url.Values{}\n", name)
		for _, p := range query {
			field := "p." + fieldName(p.Name)
			switch p.Schema.Type {
			case "string":
				g.printf("if %s != \"\" {\nv.Set(%q, %s)\n}\n", field, p.Name, field)
			case "integer":
				g.imports["strconv"] = true
				g.printf("if %s != 0 {\nv.Set(%q, strconv.Itoa(%s))\n}\n", field, p.Name, field)
			case "boolean":
				g.printf("if %s {\nv.Set(%q, \"true\")\n}\n", field, p.Name)
			}
		}
		g.printf("return v\n}\n\n")
	}
	g.printf("// %s calls %s %s", name, op.method, op.path)
	if op.Summary != "" {
		g.printf(": %s", strings.TrimSuffix(op.Summary, "."))
	}
	g.printf(".\n")
	if op.Description != "" {
		g.printf("//\n")
		g.comment(op.Description)
	}
	g.printf("func (c *Client) %s(%s) (*%s, error) {\nvar out %s\n", name, strings.Join(args, ", "), out, out)
	segments := strings.Split(op.path, "/")
	var parts []string
	literal := ""
	for i, segment := range segments {
		if i > 0 {
			literal += "/"
		}
		if strings.HasPrefix(segment, "{") && strings.HasSuffix(segment, "}") {
			parts = append(parts, fmt.Sprintf("%q", literal), "url.PathEscape("+argName(strings.Trim(segment, "{}"))+")")
			literal = ""
			continue
		}
		literal += segment
	}
	if literal != "" || len(parts) == 0 {
		parts = append(parts, fmt.Sprintf("%q", literal))
	}
	queryArg, bodyArg := "nil", "nil"
	if len(query) > 0 {
		queryArg = "params.values()"
	}
	if body != "" {
		bodyArg = "body"
	}
	g.printf("if err := c.do(ctx, %q, %s, %s, %s, &out, %t); err != nil {\nreturn nil, err\n}\nreturn &out, nil\n}\n\n", op.method, strings.Join(parts, "+"), queryArg, bodyArg, len(op.Security) > 0)
	return nil
}

// table emits the operations the relay command dispatches on, with the field
// documentation its help prints.
func (g *generator) table(ops []*operation) error {
	g.printf("var operations = []operation{\n")
	for _, op := range ops {
		path, query, body, _, err := g.signature(op)
		if err != nil {
			return err
		}
		name := methodName(op.ID)
		g.printf("{\nName: %q, Method: %q, Path: %q, Tag: %q,\nSummary: %q,\nDescription: %q,\n", commandName(op.ID), op.method, op.path, strings.Join(op.Tags, ","), op.Summary, op.Description)
		call := []string{"ctx"}
		for i := range path {
			call = append(call, fmt.Sprintf("path[%d]", i))
		}
		g.printf("Fields: []field{\n")
		for _, p := range path {
			g.printf("{Name: %q, In: \"path\", Type: \"string\", Required: true, Doc: %q},\n", p.Name, p.Description)
		}
		if body != "" {
			s := g.schemas[refName(op.body())]
			required := map[string]bool{}
			for _, n := range s.Required {
				required[n] = true
			}
			names := make([]string, 0, len(s.Properties))
			for n := range s.Properties {
				names = append(names, n)
			}
			sort.Strings(names)
			for _, n := range names {
				p := s.Properties[n]
				typ, err := g.goType(p, true, required[n])
				if err != nil {
					return err
				}
				g.printf("{Name: %q, In: \"body\", Type: %q, Required: %t, Doc: %q},\n", n, typ, required[n], p.Description)
			}
			call = append(call, "*body.(*"+body+")")
		}
		for _, p := range query {
			g.printf("{Name: %q, In: \"query\", Type: %q, Doc: %q},\n", p.Name, p.Schema.Type, p.Description)
		}
		g.printf("},\n")
		if body != "" {
			g.printf("Body: func() any { return new(%s) },\n", body)
		}
		if len(query) > 0 {
			g.printf("Params: func() any { return new(%sParams) },\n", name)
			call = append(call, "*params.(*"+name+"Params)")
		}
		g.printf("Call: func(ctx context.Context, c *Client, path []string, body, params any) (any, error) {\nreturn c.%s(%s)\n},\n},\n", name, strings.Join(call, ", "))
	}
	g.printf("}\n")
	return nil
}

var initialisms = map[string]string{
	"id": "ID", "ids": "IDs", "ip": "IP", "ips": "IPs", "url": "URL", "urls": "URLs", "api": "API",
	"asn": "ASN", "icp": "ICP", "ttl": "TTL", "sms": "SMS", "ipv4": "IPv4", "ipv6": "IPv6",
	"uuid": "UUID", "http": "HTTP", "https": "HTTPS", "json": "JSON", "ms": "MS", "rr": "RR", "cn": "CN",
}

// words splits snake_case and CamelCase (with acronym runs) into lower-case words.
func words(name string) []string {
	var out []string
	for _, part := range strings.FieldsFunc(name, func(r rune) bool { return r == '_' || r == '-' || r == ' ' }) {
		runes := []rune(part)
		start := 0
		for i := 1; i < len(runes); i++ {
			upper := func(r rune) bool { return r >= 'A' && r <= 'Z' }
			lower := func(r rune) bool { return r >= 'a' && r <= 'z' }
			if (upper(runes[i]) && lower(runes[i-1])) || (upper(runes[i]) && i+1 < len(runes) && lower(runes[i+1]) && upper(runes[i-1])) {
				out = append(out, strings.ToLower(string(runes[start:i])))
				start = i
			}
		}
		out = append(out, strings.ToLower(string(runes[start:])))
	}
	return out
}

func camel(name string) string {
	var b strings.Builder
	for _, w := range words(name) {
		if v, ok := initialisms[w]; ok {
			b.WriteString(v)
		} else if w != "" {
			b.WriteString(strings.ToUpper(w[:1]) + w[1:])
		}
	}
	return b.String()
}

func typeName(schema string) string { return camel(schema) }
func fieldName(json string) string  { return camel(json) }
func methodName(id string) string   { return camel(id) }

func commandName(id string) string { return strings.Join(words(id), "-") }

func argName(param string) string {
	name := camel(param)
	if name == "" {
		return "arg"
	}
	if v, ok := initialisms[strings.ToLower(name)]; ok && v == name {
		return strings.ToLower(name)
	}
	return strings.ToLower(name[:1]) + name[1:]
}
